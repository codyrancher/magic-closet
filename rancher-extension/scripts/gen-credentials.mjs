// Bakes the closet secret-set's credential model from the sidecar declarations
// into pkg/magic-closet/credentials.generated.ts — the single source of truth is
// workspace/sidecars/**/sidecar.yml (`credentials:`) + workspace/sidecars/
// credential-groups.yml (group order/descriptions + `core` credentials).
//
// Fields are deduped by key across sidecars; each field keeps a per-sidecar
// `usage` so the page can show "used by figma: ...; rancher-browser: ...".
//
// Run after editing any credential declaration:
//   node rancher-extension/scripts/gen-credentials.mjs
// (needs js-yaml resolvable; e.g. NODE_PATH=workspace/api/node_modules, or run
//  it from a context where js-yaml is installed). The generated file is committed
//  so normal builds don't need to run this.
import { readFileSync, readdirSync, writeFileSync, existsSync, statSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import yaml from 'js-yaml';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../..');                 // magic-closet repo root
const sidecarsDir = path.join(root, 'workspace', 'sidecars');
const outFile = path.join(here, '..', 'pkg', 'magic-closet', 'credentials.generated.ts');

const load = (p) => yaml.load(readFileSync(p, 'utf-8')) || {};

// key -> { key, label, group, usages: [{ sidecar, usage }] }
const fields = new Map();
function add(cred, sidecar) {
  if (!cred || !cred.key) return;
  let f = fields.get(cred.key);
  if (!f) {
    f = { key: cred.key, label: cred.label || cred.key, group: cred.group || 'Other', usages: [] };
    fields.set(cred.key, f);
  }
  if (cred.usage) f.usages.push({ sidecar, usage: cred.usage });
}

// Group order + descriptions, and closet-core credentials (not owned by a sidecar)
const groupsFile = path.join(sidecarsDir, 'credential-groups.yml');
const groupsDoc = existsSync(groupsFile) ? load(groupsFile) : { groups: {}, core: [] };
for (const c of groupsDoc.core || []) add(c, 'workspace');

// Every sidecar.yml under sidecars/*/ and sidecars/*/*/
function scan(dir) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    const sub = path.join(dir, entry.name);
    const yml = path.join(sub, 'sidecar.yml');
    if (existsSync(yml)) {
      const meta = load(yml);
      for (const c of meta.credentials || []) add(c, meta.name || entry.name);
    } else {
      scan(sub); // a group dir (e.g. auth/, dev/)
    }
  }
}
if (existsSync(sidecarsDir)) scan(sidecarsDir);

// Assemble groups in declared order, then any leftover groups fields referenced
const groupMeta = groupsDoc.groups || {};
const orderedNames = [...Object.keys(groupMeta)];
for (const f of fields.values()) if (!orderedNames.includes(f.group)) orderedNames.push(f.group);

const groups = orderedNames
  .map((name) => ({
    name,
    description: groupMeta[name]?.description || '',
    // strip the internal `group` tag — grouping is conveyed by the enclosing group
    fields:      [...fields.values()].filter((f) => f.group === name)
      .map(({ key, label, usages }) => ({ key, label, usages })),
  }))
  .filter((g) => g.fields.length);

const keys = [...fields.keys()];

const banner = '// AUTO-GENERATED by scripts/gen-credentials.mjs from workspace/sidecars/**. Do not edit by hand.';
const out = `${banner}
export interface CredentialUsage { sidecar: string; usage: string; }
export interface CredentialField { key: string; label: string; usages: CredentialUsage[]; }
export interface CredentialGroup { name: string; description: string; fields: CredentialField[]; }

export const CREDENTIAL_GROUPS: CredentialGroup[] = ${JSON.stringify(groups, null, 2)};

// Flat list of every credential key (for the "N/total" Keys column).
export const CREDENTIAL_KEYS: string[] = ${JSON.stringify(keys)};
`;

writeFileSync(outFile, out);
console.log(`wrote ${path.relative(root, outFile)} — ${groups.length} groups, ${keys.length} keys`);
